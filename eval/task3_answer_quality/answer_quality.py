"""
Part Two, Task 3 -- judges the REAL answers already generated by
generate_answers.py (eval/task3_answer_quality/generated_answers.json), using a SEPARATE judge
model from the one that generated them (see eval/task1_dataset/README.md /
JUDGE_MODEL note below for why: same-model self-evaluation is biased).

4 checks, each a standalone prompt file under eval/task3_answer_quality/prompts/ (kept as
files, not inline strings, so they're reviewable/versionable on their
own):
  - faithfulness:        is every claim in the answer grounded in context?
  - relevance:            does the answer actually address the question?
  - completeness:         does it cover every part the reference answer has?
  - language_correctness: right language, and does it read naturally?

should_refuse items are scored differently -- there's no "answer quality"
to judge for a question that should have been refused. Instead we record
whether the guardrail actually refused it (out_of_domain/ambiguous) or
wrongly answered it (answer_normally), a simple logical check, not an
LLM judgment.

Usage: python eval/answer_quality.py (run AFTER generate_answers.py)
"""

import json
import os
import re
import time
from collections import defaultdict
from pathlib import Path

import groq
from groq import Groq

# History: openai/gpt-oss-120b was the first choice (different
# architecture from qwen, reduces self-evaluation bias) but its daily
# quota got exhausted mid-testing. Switched to qwen/qwen3.8-27b (fast,
# no reasoning_effort needed) and used it successfully for a full run.
#
# qwen3.8-27b is no longer usable as the judge, though: after
# qwen/qwen3.6-27b (the answer-generating model) was withdrawn by Groq
# (see app/api/main.py's GROQ_MODEL note), qwen3.8-27b was promoted to
# take over answer generation itself -- using it as the judge too would
# mean the same model judging its own answers, exactly the
# self-evaluation bias this whole judge-model search was trying to
# avoid. Moved to openai/gpt-oss-20b instead: different architecture
# from qwen (real independence from the generator), already verified
# once earlier in this project (a live test: reasoning_effort="low"
# produced a correct judgment in 32 tokens / 0.39s -- MUCH cheaper than
# its own default hidden-reasoning behavior, which is what caused the
# truncated-JSON and quota problems documented in this project's
# history the first time this model was tried without that setting).
JUDGE_MODEL = "openai/gpt-oss-20b"
PROMPTS_DIR = Path("eval/task3_answer_quality/prompts")

CHECKS = ["faithfulness", "relevance", "completeness", "language_correctness"]


def load_prompt(name: str) -> str:
    return (PROMPTS_DIR / f"judge_{name}.txt").read_text(encoding="utf-8")


PROMPT_TEMPLATES = {name: load_prompt(name) for name in CHECKS}


def fill(template: str, **kwargs) -> str:
    text = template
    for key, value in kwargs.items():
        text = text.replace("{" + key + "}", str(value or ""))
    return text


def parse_judge_json(raw: str) -> dict:
    """Judge models occasionally wrap JSON in prose or code fences despite
    instructions -- extract the first {...} block rather than failing."""
    match = re.search(r"\{.*\}", raw, re.DOTALL)
    if not match:
        raise ValueError(f"No JSON object found in judge response: {raw[:200]}")
    obj = json.loads(match.group(0))
    return {"score": float(obj["score"]), "reason": str(obj.get("reason", ""))}


def call_with_rate_limit_retry(client: Groq, **create_kwargs):
    """openai/gpt-oss-120b has an 8000 tokens-per-minute cap on this
    account -- much tighter than the generation model -- so a run of
    back-to-back judge calls at max_tokens=800 trips groq.RateLimitError
    partway through a 256-call batch. Groq's error message names exactly
    how long to wait (e.g. "try again in 367.5ms"); parse and sleep that
    long (plus a safety margin) instead of crashing the whole run, and
    retry a few times before giving up for real."""
    MAX_RETRIES = 5
    for attempt in range(MAX_RETRIES):
        try:
            return client.chat.completions.create(**create_kwargs)
        except groq.RateLimitError as e:
            wait_s = 2.0 * (attempt + 1)  # fallback if we can't parse a wait time
            # Groq phrases this two ways depending on the limit hit:
            # per-minute -> "try again in 367.5ms" / "try again in 2s"
            # per-day    -> "try again in 14m51.6s" (minutes+seconds)
            msg = str(e)
            minute_match = re.search(r"try again in (?:(\d+)m)?([\d.]+)(ms|s)\b", msg)
            if minute_match:
                minutes = float(minute_match.group(1) or 0)
                value, unit = float(minute_match.group(2)), minute_match.group(3)
                wait_s = minutes * 60 + (value / 1000 if unit == "ms" else value) + 0.5
            print(f"    [rate limited, waiting {wait_s:.1f}s, attempt {attempt+1}/{MAX_RETRIES}]")
            time.sleep(wait_s)
    # Last attempt, let it raise if it still fails -- a real, non-rate-limit
    # problem at that point shouldn't be silently swallowed.
    return client.chat.completions.create(**create_kwargs)


def run_judge(client: Groq, check: str, **fill_kwargs) -> dict:
    # gpt-oss-20b spends most of its budget on hidden chain-of-thought
    # reasoning BY DEFAULT -- that default behavior is what caused
    # truncated-JSON responses and slow/expensive calls the first time
    # this model was used in this project. reasoning_effort="low" (the
    # lowest this model accepts) skips nearly all of that: a live test
    # against a real judge prompt used only 32 tokens and took 0.39s,
    # vs. hundreds of tokens and several seconds without it. 300
    # max_tokens is generous headroom at that point, not a tight squeeze
    # -- retrying once on a parse failure still guards the rare case
    # that runs long anyway.
    prompt = fill(PROMPT_TEMPLATES[check], **fill_kwargs)
    for attempt in range(2):
        resp = call_with_rate_limit_retry(
            client,
            model=JUDGE_MODEL,
            messages=[{"role": "user", "content": prompt}],
            temperature=0,
            max_tokens=300,
            reasoning_effort="low",
        )
        raw = resp.choices[0].message.content
        try:
            return parse_judge_json(raw)
        except Exception as e:
            last_error = e
    return {"score": None, "reason": f"[judge parse error after retry: {last_error}]"}


def context_text(retrieved_chunks: list[dict]) -> str:
    return "\n\n".join(c.get("text", "") for c in retrieved_chunks)


def score_answerable_item(client: Groq, item: dict) -> dict:
    context = context_text(item["retrieved_chunks"])
    common = {
        "question": item["question"],
        "context": context,
        "answer": item["answer_text"],
        "expected_answer": item.get("expected_answer"),
    }
    scores = {
        "faithfulness": run_judge(client, "faithfulness", context=context, question=item["question"], answer=item["answer_text"]),
        "relevance": run_judge(client, "relevance", question=item["question"], context=context, answer=item["answer_text"]),
        "completeness": run_judge(client, "completeness", question=item["question"], expected_answer=item.get("expected_answer"), answer=item["answer_text"]),
        "language_correctness": run_judge(client, "language_correctness", question=item["question"], answer=item["answer_text"]),
    }
    return {
        "id": item["id"], "language": item["language"], "type": item["type"],
        "question": item["question"], "answer": item["answer_text"],
        "scores": {k: v["score"] for k, v in scores.items()},
        "reasons": {k: v["reason"] for k, v in scores.items()},
    }


def score_should_refuse_item(item: dict) -> dict:
    correctly_refused = item["guardrail_action"] in ("out_of_domain", "ambiguous", "no_info")
    return {
        "id": item["id"], "language": item["language"], "type": item["type"],
        "question": item["question"], "answer": item["answer_text"],
        "guardrail_action": item["guardrail_action"],
        "correctly_refused": correctly_refused,
    }


def aggregate_answerable(results: list[dict], group_key) -> dict:
    groups = defaultdict(list)
    for r in results:
        groups[group_key(r)].append(r)
    summary = {}
    for key, items in groups.items():
        n = len(items)
        entry = {"n": n}
        for check in CHECKS:
            valid = [it["scores"][check] for it in items if it["scores"][check] is not None]
            entry[check] = sum(valid) / len(valid) if valid else None
        summary[key] = entry
    return summary


OUT_PATH = Path("eval/task3_answer_quality/answer_quality_raw.json")


def save_progress(answerable_results: list[dict], refuse_results: list[dict], done: bool) -> None:
    """Writes the full output after EVERY item, not just at the end.
    A prior run got killed (RateLimitError backoff made it look stuck) and
    lost all ~57 already-judged items because the old version only wrote
    once, at the very end -- this makes an interrupted run keep whatever
    it already finished, at the small, cheap cost of rewriting a ~70KB
    file each iteration."""
    by_language = aggregate_answerable(answerable_results, lambda r: r["language"]) if answerable_results else {}
    by_type_language = aggregate_answerable(answerable_results, lambda r: f"{r['type']}_{r['language']}") if answerable_results else {}

    refuse_by_language = defaultdict(lambda: {"n": 0, "correctly_refused": 0})
    for r in refuse_results:
        b = refuse_by_language[r["language"]]
        b["n"] += 1
        b["correctly_refused"] += 1 if r["correctly_refused"] else 0

    out = {
        "judge_model": JUDGE_MODEL,
        "complete": done,
        "by_language": by_language,
        "by_type_language": by_type_language,
        "should_refuse_by_language": {k: v for k, v in refuse_by_language.items()},
        "per_item_answerable": answerable_results,
        "per_item_should_refuse": refuse_results,
    }
    OUT_PATH.write_text(json.dumps(out, ensure_ascii=False, indent=2), encoding="utf-8")


def run():
    client = Groq(api_key=os.environ["GROQ_API_KEY"])
    generated = json.loads(Path("eval/task3_answer_quality/generated_answers.json").read_text(encoding="utf-8"))

    answerable = [g for g in generated if g["type"] != "should_refuse"]
    refuse_items = [g for g in generated if g["type"] == "should_refuse"]

    print(f"Judging {len(answerable)} answerable items with {JUDGE_MODEL} "
          f"({len(answerable) * 4} judge calls)...")

    answerable_results = []
    refuse_results = []
    for i, item in enumerate(answerable, 1):
        r = score_answerable_item(client, item)
        answerable_results.append(r)
        s = r["scores"]
        print(f"[{i}/{len(answerable)}] {item['id']} ({item['language']}/{item['type']}) "
              f"-> faith={s['faithfulness']} rel={s['relevance']} "
              f"comp={s['completeness']} lang={s['language_correctness']}")
        save_progress(answerable_results, refuse_results, done=False)

    print(f"\nChecking {len(refuse_items)} should_refuse items (logical check, no LLM call)...")
    for item in refuse_items:
        r = score_should_refuse_item(item)
        refuse_results.append(r)
        print(f"  {r['id']} ({r['language']}) -> {r['guardrail_action']} "
              f"-> {'OK' if r['correctly_refused'] else 'WRONGLY ANSWERED'}")
        save_progress(answerable_results, refuse_results, done=False)

    save_progress(answerable_results, refuse_results, done=True)

    by_language = aggregate_answerable(answerable_results, lambda r: r["language"])
    by_type_language = aggregate_answerable(answerable_results, lambda r: f"{r['type']}_{r['language']}")

    refuse_by_language = defaultdict(lambda: {"n": 0, "correctly_refused": 0})
    for r in refuse_results:
        b = refuse_by_language[r["language"]]
        b["n"] += 1
        b["correctly_refused"] += 1 if r["correctly_refused"] else 0

    # Final write already happened via save_progress(..., done=True) above --
    # this is just recomputed here for the printed summary below.
    print(f"\n[SAVED] {OUT_PATH}")

    print("\n=== By language ===")
    for lang, m in by_language.items():
        print(f"{lang}: n={m['n']} " + " ".join(f"{c}={m[c]:.3f}" if m[c] is not None else f"{c}=N/A" for c in CHECKS))

    print("\n=== should_refuse correctness ===")
    for lang, b in refuse_by_language.items():
        print(f"{lang}: {b['correctly_refused']}/{b['n']} correctly refused")


if __name__ == "__main__":
    run()
